const pick = (s) => (/^fr/i.test(String(s || "").trim()) ? "fr" : /^en/i.test(String(s || "").trim()) ? "en" : null);
// langue d'une requête : X-Folio-Lang, puis première langue connue d'Accept-Language, sinon français
function langOf(req) {
  const h = pick(req.headers["x-folio-lang"]);
  if (h) return h;
  for (const part of String(req.headers["accept-language"] || "").split(",")) {
    const l = pick(part);
    if (l) return l;
  }
  return "fr";
}
function t(lang, key, vars = {}) {
  const s = (M[lang] || M.fr)[key] ?? M.fr[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}
module.exports = { langOf, t, pick };
